// package JAVA.THEORY_JAVA.5_OPERATORS;

public class datatype {
    public static void main(String[] args){
        /*
         * DATA TYPE ----------------------------------------------------------------
         *  byte + short == int
         * short + int == int
         * long + float == float
         * float + double == double
         * long + double == double
         * double + double == double
         * char + short == int
         * char + int == int
         * int + float == float
         * 
         * 
         * INCREMENT AND DECREMENT----------------------------------------------------------------
         * a++ (print then add),      ++a(add then print),          Increment
         * a-- (print then subtract), --a(subtract then print)      Decrement
         */

         int a = 56;
         System.out.println(a);
         System.out.println(a++);
         System.out.println(a);
         System.out.println(++a);
         System.out.println(a);
    }
}
