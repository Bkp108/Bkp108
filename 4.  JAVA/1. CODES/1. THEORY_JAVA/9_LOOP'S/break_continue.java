public class break_continue {
    public static void main(String[] args) {
        for (int i = 0; i < 5; i++) {
            System.out.println(i);
            System.out.println("----------------------");

            if (i == 3) {
                System.out.println("Ending the loop");
                break;
            }

             
        }
    }
}
